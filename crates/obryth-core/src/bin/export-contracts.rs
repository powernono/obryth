use obryth_core::*;
use ts_rs::TS;
fn main() -> anyhow::Result<()> {
    let config = ts_rs::Config::default();
    let declarations = [
        Note::decl(&config),
        NoteDraft::decl(&config),
        KnowledgeScope::decl(&config),
        NoteQuery::decl(&config),
        SearchHit::decl(&config),
        ActivityQuery::decl(&config),
        ActivityPageQuery::decl(&config),
        ActivityDay::decl(&config),
        ActivitySummary::decl(&config),
        ActivityCard::decl(&config),
        ActivityFeed::decl(&config),
        ActivityVersion::decl(&config),
        ActivityVersions::decl(&config),
        ProviderProfile::decl(&config),
        SyncReport::decl(&config),
        PaneSpec::decl(&config),
    ];
    let source = format!(
        "// Generated by cargo run -p obryth-core --bin export-contracts.\n{}\n",
        declarations
            .iter()
            .map(|s| format!("export {s}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/contracts/src/generated.ts");
    std::fs::create_dir_all(root.parent().unwrap())?;
    std::fs::write(root, source)?;
    Ok(())
}
